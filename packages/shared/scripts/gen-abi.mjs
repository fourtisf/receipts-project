// Generates typed ABI modules from Foundry build output (packages/contracts/out) into src/abi.
// ABIs are never hand-written. Run `pnpm abi:gen` after `forge build`.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../contracts/out');
const abiDir = resolve(here, '../src/abi');
const contracts = [
  ['SignalRegistry.sol', 'SignalRegistry', 'signalRegistryAbi'],
  ['ReceiptsVault.sol', 'ReceiptsVault', 'receiptsVaultAbi'],
  ['VaultFactory.sol', 'VaultFactory', 'vaultFactoryAbi'],
  ['IExternal.sol', 'AggregatorV3Interface', 'aggregatorV3Abi'],
  ['IExternal.sol', 'ISwapRouter02', 'swapRouter02Abi'],
  ['IERC20.sol', 'IERC20', 'erc20Abi'],
];
if (!existsSync(outDir)) {
  console.error(`No Foundry output at ${outDir}. Run \`forge build\` in packages/contracts first.`);
  process.exit(1);
}
mkdirSync(abiDir, { recursive: true });
const index = [];
for (const [file, name, exportName] of contracts) {
  const path = resolve(outDir, file, `${name}.json`);
  if (!existsSync(path)) {
    console.error(`Missing artifact ${path}`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(path, 'utf8'));
  const body =
    `// AUTO-GENERATED from packages/contracts/out/${file}/${name}.json by scripts/gen-abi.mjs — do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(resolve(abiDir, `${name}.ts`), body);
  index.push(`export { ${exportName} } from './${name}.js';`);
}
writeFileSync(
  resolve(abiDir, 'index.ts'),
  `// AUTO-GENERATED by scripts/gen-abi.mjs — do not edit.\n${index.join('\n')}\n`,
);
console.log(`Wrote ${contracts.length} ABIs to ${abiDir}`);
